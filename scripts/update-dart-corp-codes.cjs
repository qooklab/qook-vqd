/** Refresh the bundled stock -> corporation IDs from FSS's public company search.
 * No OpenDART API key is required. Runtime collection must not depend on this HTML endpoint.
 */
const fs = require("node:fs");
const path = require("node:path");
const Module = require("node:module");
const ts = require("typescript");
const root = path.resolve(__dirname, "..");
const file = path.join(root, "lib/stocks.ts");
const m = new Module(file, module);
m.filename = file;
m.paths = Module._nodeModulePaths(path.dirname(file));
m._compile(
  ts.transpileModule(fs.readFileSync(file, "utf8"), {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020,
    },
  }).outputText,
  file,
);
const stocks = m.exports.stocks;
const canonical = (code) => (code === "005935" ? "005930" : code);
async function lookup(code) {
  const source = "https://dart.fss.or.kr/dsae001/search.ax?textCrpNm=" + code;
  const response = await fetch(source, { signal: AbortSignal.timeout(15000) });
  if (!response.ok)
    throw Error("FSS company search HTTP " + response.status + " for " + code);
  const html = await response.text();
  const matches = [];
  for (const row of html.matchAll(/<tr\b[^>]*>([\s\S]*?)<\/tr>/gi)) {
    const cells = [...row[1].matchAll(/<td\b[^>]*>([\s\S]*?)<\/td>/gi)].map(
      (x) => x[1],
    );
    if (cells.length < 2) continue;
    const ticker = cells[1].replace(/<[^>]*>/g, "").trim();
    const corp = cells[0].match(
      /(?:javascript:)?select\(['"](\d{8})['"]\)/,
    )?.[1];
    if (ticker === code && corp) matches.push(corp);
  }
  if (matches.length !== 1)
    throw Error(
      "Expected one exact ticker match for " +
        code +
        ", found " +
        matches.length,
    );
  return { stockCode: code, corpCode: matches[0], source };
}
(async () => {
  const pending = [...new Set(stocks.map(([, code]) => canonical(code)))],
    verified = new Map();
  async function worker() {
    while (pending.length) {
      const code = pending.shift();
      const item = await lookup(code);
      verified.set(code, item);
    }
  }
  await Promise.all([worker(), worker()]);
  const checkedOn = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Seoul",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(new Date());
  const snapshot = {
    checkedOn,
    source: "FSS DART public company search; exact stock-code match",
    entries: stocks.map(([name, code]) => ({
      name,
      ...verified.get(canonical(code)),
      stockCode: code,
      ...(canonical(code) !== code ? { issuerStockCode: canonical(code) } : {}),
    })),
  };
  const output =
    "// Generated by scripts/update-dart-corp-codes.cjs.\n// FSS public company search, exact stock-code matching. Verified " +
    checkedOn +
    ".\n// 005935 is Samsung Electronics preferred stock and shares its issuer corporation.\nexport const verifiedCorpCodes: Readonly<Partial<Record<string,string>>> = " +
    JSON.stringify(
      Object.fromEntries(
        snapshot.entries.map((x) => [x.stockCode, x.corpCode]),
      ),
      null,
      2,
    ) +
    ";\n";
  fs.mkdirSync(path.join(root, "docs/data"), { recursive: true });
  fs.writeFileSync(path.join(root, "lib/dart-corp-codes.ts"), output);
  fs.writeFileSync(
    path.join(root, "docs/data/dart-corp-codes.json"),
    JSON.stringify(snapshot, null, 2) + "\n",
  );
  console.log(
    "Verified " +
      snapshot.entries.length +
      " registered stocks from " +
      verified.size +
      " FSS company records (" +
      checkedOn +
      ").",
  );
  for (const item of snapshot.entries)
    console.log(item.stockCode + " " + item.name + " -> " + item.corpCode);
})().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
